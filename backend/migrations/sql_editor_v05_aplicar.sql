-- 7. Exposicao / RLS (SEG-12, SEG-20)
--    Padrao do repositorio: o REVOKE e feito na propria migracao (como no 0001, sem impacto na API, que conecta
--    como dono); ligar RLS e OPCIONAL/separado (0005_rls_opcional.sql), pois depende de confirmar que o usuario do
--    DATABASE_URL e dono/BYPASSRLS. Aqui o RLS nas 2 tabelas novas (SEM policies) so e ligado se:
--      (a) a sessao declarou  SET fast_ariam.habilitar_rls = 'sim';   OU
--      (b) o RLS ja esta ligado em ordem_servico (0005 aplicado -> usuario ja validado).
--    Caso contrario, emite NOTICE e o 0005 (lista atualizada) / o comando manual cobre as tabelas novas.
--    NAO usar FORCE ROW LEVEL SECURITY. Depois, rodar get_advisors do Supabase.
-- -----------------------------------------------------------------------------
DO $mig$
DECLARE
  t text;
  v_seq text;
  v_forcar boolean := coalesce(current_setting('fast_ariam.habilitar_rls', true), '') = 'sim';
  v_rls_ja boolean;
BEGIN
  -- REVOKE (so se os papeis do Supabase existirem; em PostgreSQL local nao existem)
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon')
     AND EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
    FOREACH t IN ARRAY ARRAY['equipamento_modelo', 'os_equipamento']
    LOOP
      EXECUTE format('REVOKE ALL ON TABLE public.%I FROM anon, authenticated', t);
      -- sequence da identity (pg_get_serial_sequence ja devolve o nome qualificado e quotado)
      v_seq := pg_get_serial_sequence('public.' || t, CASE t WHEN 'equipamento_modelo' THEN 'id_equipamento_modelo'
                                                             ELSE 'id_os_equipamento' END);
      IF v_seq IS NOT NULL THEN
        EXECUTE format('REVOKE ALL ON SEQUENCE %s FROM anon, authenticated', v_seq);
      END IF;
    END LOOP;
  ELSE
    RAISE NOTICE '0007: papeis anon/authenticated inexistentes (nao e Supabase?); REVOKE ignorado.';
  END IF;

  -- RLS sem policies (opcional/condicional - ver cabecalho da secao)
  SELECT c.relrowsecurity INTO v_rls_ja FROM pg_class c WHERE c.oid = 'public.ordem_servico'::regclass;
  IF v_forcar OR coalesce(v_rls_ja, false) THEN
    FOREACH t IN ARRAY ARRAY['equipamento_modelo', 'os_equipamento']
    LOOP
      EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
    END LOOP;
    RAISE NOTICE '0007: RLS ligado (sem policies) em equipamento_modelo e os_equipamento.';
  ELSE
    RAISE NOTICE '0007: RLS NAO ligado nas tabelas novas (0005 ainda nao aplicado e fast_ariam.habilitar_rls <> sim). '
                 'Quando confirmar o usuario do DATABASE_URL: ALTER TABLE public.equipamento_modelo ENABLE ROW LEVEL SECURITY; '
                 'ALTER TABLE public.os_equipamento ENABLE ROW LEVEL SECURITY;';
  END IF;
END
$mig$;

