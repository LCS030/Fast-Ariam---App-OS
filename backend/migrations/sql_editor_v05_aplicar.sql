-- 3. Trigger de consistencia (SDD 4.8): o equipamento deve pertencer a MESMA OS da visita.
--    Uma FK simples nao garante isso. Erro 23514 (check_violation). Linha sem vinculo (legado) passa.
--    Limitacao: nao cobre alterar visita.id_os depois (a API nao faz isso).
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.fn_servico_equip_mesma_os()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $fn$
DECLARE
  v_os_visita integer;
  v_os_equip  integer;
BEGIN
  IF NEW.id_os_equipamento IS NULL THEN
    RETURN NEW;
  END IF;

  SELECT v.id_os INTO v_os_visita FROM public.visita v WHERE v.id_visita = NEW.id_visita;
  SELECT oe.id_os INTO v_os_equip FROM public.os_equipamento oe WHERE oe.id_os_equipamento = NEW.id_os_equipamento;

  IF v_os_visita IS DISTINCT FROM v_os_equip THEN
    RAISE EXCEPTION 'os_equipamento % pertence a OS % mas a visita % pertence a OS %',
      NEW.id_os_equipamento, v_os_equip, NEW.id_visita, v_os_visita
      USING ERRCODE = '23514';
  END IF;

  RETURN NEW;
END
$fn$;

DROP TRIGGER IF EXISTS trg_servico_equip_mesma_os ON public.servico_equipamento;
CREATE TRIGGER trg_servico_equip_mesma_os
  BEFORE INSERT OR UPDATE OF id_visita, id_os_equipamento ON public.servico_equipamento
  FOR EACH ROW EXECUTE FUNCTION public.fn_servico_equip_mesma_os();

