-- -----------------------------------------------------------------------------
-- 6a. Backfill de os_equipamento (SDD 4.9 passo 5): origem = 'backfill_legado'.
--     Varias visitas da mesma OS com a mesma serie geram UM os_equipamento (DISTINCT ON por OS + upper(serie),
--     escolhendo o servico de menor id_servico para definir serie/modelo). Serie nula/vazia fica de fora.
-- -----------------------------------------------------------------------------
WITH base AS (
  SELECT se.id_servico,
         v.id_os,
         btrim(se.numero_serie_atendido) AS serie,
         COALESCE(NULLIF(btrim(se.nome_equipamento), ''), 'Não catalogado') AS modelo_nome
    FROM public.servico_equipamento se
    JOIN public.visita v ON v.id_visita = se.id_visita
   WHERE se.id_os_equipamento IS NULL
     AND v.id_os IS NOT NULL
     AND se.numero_serie_atendido IS NOT NULL
     AND btrim(se.numero_serie_atendido) <> ''
), escolhido AS (
  SELECT DISTINCT ON (b.id_os, upper(b.serie)) b.id_os, b.serie, b.modelo_nome
    FROM base b
   ORDER BY b.id_os, upper(b.serie), b.id_servico
)
INSERT INTO public.os_equipamento (id_os, id_equipamento_modelo, numero_serie, origem)
SELECT e.id_os, m.id_equipamento_modelo, e.serie, 'backfill_legado'
  FROM escolhido e
  JOIN public.equipamento_modelo m ON lower(m.modelo) = lower(e.modelo_nome)
ON CONFLICT DO NOTHING;   -- conflito no indice unico funcional (id_os, upper(numero_serie))

-- -----------------------------------------------------------------------------
-- 6b. Backfill do vinculo (SDD 4.9 passos 6 e 7): somente onde id_os_equipamento IS NULL.
--     Vincula so se serie E modelo (por lower) coincidem com o os_equipamento da mesma OS; e, por
--     UNIQUE (id_visita, id_os_equipamento), so UM servico por visita/equipamento (o de menor id_servico).
--     EXCECOES permanecem is_legado = true com numero_serie_atendido preservado: sem serie, sem nome (se o
--     'Não catalogado' foi desabilitado), duplicata na mesma visita, serie conflitante (nome diferente).
-- -----------------------------------------------------------------------------
WITH cand AS (
  SELECT se.id_servico,
         oe.id_os_equipamento,
         row_number() OVER (PARTITION BY se.id_visita, oe.id_os_equipamento ORDER BY se.id_servico) AS rn
    FROM public.servico_equipamento se
    JOIN public.visita v ON v.id_visita = se.id_visita
    JOIN public.os_equipamento oe
      ON oe.id_os = v.id_os
     AND upper(oe.numero_serie) = upper(btrim(se.numero_serie_atendido))
    JOIN public.equipamento_modelo m
      ON m.id_equipamento_modelo = oe.id_equipamento_modelo
     AND lower(m.modelo) = lower(COALESCE(NULLIF(btrim(se.nome_equipamento), ''), 'Não catalogado'))
   WHERE se.id_os_equipamento IS NULL
     AND se.numero_serie_atendido IS NOT NULL
     AND btrim(se.numero_serie_atendido) <> ''
     AND NOT EXISTS (SELECT 1 FROM public.servico_equipamento x      -- idempotencia / nao violar o UNIQUE
                      WHERE x.id_visita = se.id_visita
                        AND x.id_os_equipamento = oe.id_os_equipamento)
)
UPDATE public.servico_equipamento se
   SET id_os_equipamento = c.id_os_equipamento,
       is_legado = false
  FROM cand c
 WHERE se.id_servico = c.id_servico
   AND c.rn = 1
   AND se.id_os_equipamento IS NULL;

