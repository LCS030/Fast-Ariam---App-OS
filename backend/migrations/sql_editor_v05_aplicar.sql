  (select count(*) from information_schema.columns
    where table_schema = 'public' and table_name = 'servico_equipamento'
      and column_name in ('id_os_equipamento', 'conserto_salvo_em', 'is_legado')) as colunas_novas,
  (select count(*) from pg_proc where proname = 'fn_servico_equip_mesma_os') as funcao,
  (select count(*) from pg_trigger where tgname = 'trg_servico_equip_mesma_os' and not tgisinternal) as trigger_;

-- C2. Constraints e indices novos (todas devem aparecer com convalidated = true)
select conrelid::regclass::text as tabela, conname, contype, convalidated
  from pg_constraint
 where conrelid in ('public.equipamento_modelo'::regclass, 'public.os_equipamento'::regclass,
                    'public.sync_arquivo'::regclass, 'public.servico_equipamento'::regclass)
   and contype in ('c', 'u', 'f')
 order by 1, 2;

-- C3. RLS ligado (sem policies) nas 3 tabelas novas, e anon/authenticated sem acesso
select c.relname, c.relrowsecurity as rls_ligado,
       has_table_privilege('anon', c.oid, 'select') as anon_le,
       has_table_privilege('authenticated', c.oid, 'select') as authenticated_le
  from pg_class c
 where c.relnamespace = 'public'::regnamespace and c.relname in ('equipamento_modelo', 'os_equipamento', 'sync_arquivo')
 order by 1;

-- C4. Nada existente foi alterado: compara com os checksums do "ANTES" (valido se ninguem usou o sistema no intervalo)
select t, n, case when h = esperado then 'OK (identico ao antes)' else 'DIVERGIU - conferir se houve uso no intervalo' end as resultado
  from (
    select 'cliente' t, count(*) n, md5(coalesce(string_agg(x::text, '|' order by id_cliente), '')) h, '563906c7d7063f5501ebba0a4c55a302' esperado from public.cliente x
    union all select 'custo_os', count(*), md5(coalesce(string_agg(x::text, '|' order by id_os), '')), 'a28a8f696e0a3af2cd2c3d7c637f983e' from public.custo_os x
    union all select 'log_acao', count(*), md5(coalesce(string_agg(x::text, '|' order by id), '')), '8483132205109624f8b72135d2854122' from public.log_acao x
    union all select 'ordem_servico', count(*), md5(coalesce(string_agg(x::text, '|' order by id_os), '')), 'f85a4f82d291ab44b687e64d97a5d9a9' from public.ordem_servico x
    union all select 'tecnico', count(*), md5(coalesce(string_agg(x::text, '|' order by id_tecnico), '')), '8e3a6e5cbc72dcda31bd59e1370ef6c1' from public.tecnico x
    union all select 'visita', count(*), md5(coalesce(string_agg(x::text, '|' order by id_visita), '')), '236da2b8fcedc1599cf09cd4ee3d0608' from public.visita x
  ) q
 order by t;

